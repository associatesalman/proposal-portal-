// Phase 7 checks: outage handling, rate limiting, storage cleanup, proposal
// deletion, cross-lead isolation, link/preview safety and real PDF fixtures.
//
//   npm run build
//   PDF_FIXTURES_DIR=<dir> npm run test:hardening     (fixtures: see below)
//
// How it works (nothing shared is stopped or reconfigured):
// - A DEDICATED app server is started on APP_PORT (default 3101) from the
//   current build. Its server-side Supabase traffic goes through a small
//   HTTP proxy run by this script (SUPABASE_SERVER_URL), which can forward,
//   refuse connections, hang, or fail only the rate limiter. That is how a
//   Supabase outage is simulated; the real local Supabase stack and any
//   other containers keep running untouched.
// - That server gets small, test-only rate limits (env) so thresholds can
//   be reached quickly. Distinct client addresses are simulated with
//   X-Forwarded-For (TEST-NET addresses), which this server trusts as-is
//   because no trusted proxy is configured — exactly the local default.
// - Authorization is always checked with real user sessions. The secret
//   key is used only for fixture setup/inspection and cleanup.
// - Destructive storage cleanup runs ONLY under a disposable user's prefix.
// - Real PDF fixtures (encrypted with pdfkit's Standard Security Handler,
//   CJK fonts, image-heavy, size/page limits) are generated by
//   supabase/tests/fixtures/make-pdf-fixtures.mjs; set PDF_FIXTURES_DIR to
//   its output folder. Without it those checks are skipped (and reported).

