function parseFlight(text) {
  const rows = new Map();
  for (const line of text.split("\n")) {
    const m = /^([0-9a-f]+):([[{].*)$/.exec(line);
    if (m) rows.set(m[1], m[2]);
  }
  const head = JSON.parse(rows.get("0") ?? "{}");
  const ref = typeof head.a === "string" && head.a.startsWith("$@") ? head.a.slice(2) : null;
  return ref ? JSON.parse(rows.get(ref)) : head.a;
}

// Calls the real login server action (same encoding the browser uses).
async function loginHttp({ email, password, ip = testIp(), next = "/dashboard" }) {
  const form = new FormData();
  form.set("email", email);
  form.set("password", password);
  form.set("next", next);
  const body = await encodeReply([{ status: "idle" }, form]);
  const started = performance.now();
  const res = await fetch(`${APP_URL}/login`, {
    method: "POST",
    headers: { "next-action": loginActionId, accept: "text/x-component", origin: APP_URL, "x-forwarded-for": ip },
    body,
    redirect: "manual",
  });
  const ms = performance.now() - started;
  const text = await res.text();
  const redirected = res.headers.get("x-action-redirect");
  return { status: res.status, ms, redirected, state: redirected ? null : parseFlight(text), setCookie: res.headers.getSetCookie() };
}

async function page(path, { cookie, ip = testIp(), headers = {} } = {}) {
  const started = performance.now();
  const res = await fetch(`${APP_URL}${path}`, {
    headers: { ...(cookie ? { cookie } : {}), "x-forwarded-for": ip, ...headers },
    redirect: "manual",
  });
  const body = Buffer.from(await res.arrayBuffer());
  return { res, ms: performance.now() - started, body, text: body.toString("utf8"), setCookie: res.headers.getSetCookie() };
}

