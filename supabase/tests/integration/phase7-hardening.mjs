// Limits use fixed windows aligned to the epoch (rate_limit_consume), so a
// burst that straddles a boundary is split across two windows (a known
// property of fixed windows: up to 2x the limit at a boundary). Threshold
// checks therefore start early in a window.
async function freshWindow(windowSeconds, neededSeconds) {
  const into = (Date.now() / 1000) % windowSeconds;
  if (windowSeconds - into < neededSeconds) await sleep((windowSeconds - into) * 1000 + 250);
}

// Marks the stored session as expired so the next request must refresh it.
function expireSession(user) {
  const names = [...user.jar.keys()].filter((n) => /-auth-token(\.\d+)?$/.test(n)).sort();
  const base = names[0].replace(/\.\d+$/, "");
  let raw = names.map((n) => user.jar.get(n)).join("");
  raw = raw.startsWith("base64-") ? Buffer.from(raw.slice(7), "base64url").toString("utf8") : raw;
  const session = JSON.parse(raw);
  session.expires_at = Math.floor(Date.now() / 1000) - 120;
  for (const n of names) user.jar.delete(n);
  user.jar.set(base, `base64-${Buffer.from(JSON.stringify(session)).toString("base64url")}`);
  user.cookie = [...user.jar].map(([n, v]) => `${n}=${v}`).join("; ");
  return session.refresh_token;
}

async function pdfWithPages(n, label = "P7") {
  const doc = await PDFDocument.create();
  for (let i = 0; i < n; i++) doc.addPage([300, 400]).drawText(`${label} page ${i + 1}`, { x: 20, y: 360, size: 14 });
  return Buffer.from(await doc.save());
}

// Upload through the real flow: ticket -> signed upload -> verify.
async function uploadPdf(user, proposalId, bytes, { expectedRevision = null, declaredSize = bytes.length } = {}) {
  const ticket = await act(user, "prepareUploadAction", { proposalId, sizeBytes: declaredSize });
  if (!ticket.ok) return { stage: "prepare", ...ticket };
  const { error } = await anon.storage
    .from(BUCKET)
    .uploadToSignedUrl(ticket.data.path, ticket.data.token, new Blob([bytes], { type: "application/pdf" }), { contentType: "application/pdf" });
  if (error) return { stage: "upload", ok: false, message: error.message, path: ticket.data.path };
  const started = performance.now();
  const done = await act(user, "completeUploadAction", { proposalId, revision: ticket.data.revision, expectedRevision, fileName: "fixture.pdf" });
  return { stage: "complete", ...done, ms: performance.now() - started, path: ticket.data.path, revision: ticket.data.revision };
}

