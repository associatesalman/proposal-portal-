// Outage proxy in front of local Supabase
// ---------------------------------------------------------------------------
const upstream = new URL(API_URL);
let mode = "forward"; // forward | refuse | hang | limiter-down
const hanging = new Set();
// Token (refresh/sign-in) requests that actually reached Supabase.
let tokenRequestsForwarded = 0;
const proxy = http.createServer((req, res) => {
  if (mode === "refuse") return req.socket.destroy();
  if (mode === "hang") {
    hanging.add(res);
    res.on("close", () => hanging.delete(res));
    return;
  }
  if (mode === "limiter-down" && req.url.startsWith("/rest/v1/rpc/rate_limit_consume")) {
    res.writeHead(503, { "content-type": "application/json" });
    return res.end('{"message":"simulated limiter outage"}');
  }
  if (req.url.startsWith("/auth/v1/token")) tokenRequestsForwarded += 1;
  const forward = http.request(
    { host: upstream.hostname, port: upstream.port, method: req.method, path: req.url, headers: { ...req.headers, host: upstream.host } },
    (up) => {
      res.writeHead(up.statusCode, up.headers);
      up.pipe(res);
    },
  );
  forward.on("error", () => res.destroy());
  req.pipe(forward);
});
function setMode(next) {
  mode = next;
  if (next !== "hang") for (const res of hanging) res.destroy();
}

